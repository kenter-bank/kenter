#[contracttype]
enum DataKey {
    Pk,
}

#[contracterror]
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
#[repr(u32)]
pub enum Error {
    BadBeacon = 1,
}

#[contract]
pub struct DrandSpike;

#[contractimpl]
impl DrandSpike {
    /// `pk`: drand's group key, uncompressed G2.
    pub fn __constructor(e: Env, pk: BytesN<192>) {
        e.storage().instance().set(&DataKey::Pk, &pk);
    }

    /// Verify round `round`'s signature (uncompressed G1) and return the seed
    /// material it yields, `sha256(sig)`. Fails `BadBeacon` on anything else.
    pub fn verify(e: Env, round: u64, sig: BytesN<96>) -> Result<BytesN<32>, Error> {
        let pk: BytesN<192> = e.storage().instance().get(&DataKey::Pk).unwrap();
        let bls = e.crypto().bls12_381();
        let msg = e.crypto().sha256(&Bytes::from_array(&e, &round.to_be_bytes()));
        let hm = bls.hash_to_g1(&msg.to_bytes().into(), &Bytes::from_slice(&e, DST));
        // Both points are subgroup-checked by the host on the way in
        // (`checked_g1_vec_from_vecobj`), so a malformed signature traps
        // rather than verifying.
        let ok = bls.pairing_check(
            vec![&e, G1Affine::from_bytes(sig.clone()), hm],
            vec![
                &e,
                G2Affine::from_bytes(BytesN::from_array(&e, &NEG_G2)),
                G2Affine::from_bytes(pk),
            ],
        );
        if !ok {
            return Err(Error::BadBeacon);
        }
        Ok(e.crypto().sha256(&sig.into()).to_bytes())
    }
}

