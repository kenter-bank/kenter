#![no_std]
//! Spike: verify one drand quicknet
//! round on Soroban, and measure what it costs. Not deployed and not part of
//! the mint. If it fits, the same few lines move into `seed_print`.
//!
//! quicknet signs `sha256(round as u64, big-endian)` with BLS12-381 on G1,
//! its group key on G2, scheme `bls-unchained-g1-rfc9380`. The check is
//! `e(sig, -g2) * e(H(m), pk) == 1`.

use soroban_sdk::{
    contract, contracterror, contractimpl, contracttype,
    crypto::bls12_381::{G1Affine, G2Affine},
    vec, Bytes, BytesN, Env,
};

/// quicknet's hash-to-curve domain separation tag (RFC 9380, G1).
pub const DST: &[u8] = b"BLS_SIG_BLS12381G1_XMD:SHA-256_SSWU_RO_NUL_";

