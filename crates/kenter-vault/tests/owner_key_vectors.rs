//! Owner-key derivation, pinned for the card.
//!
//! The companion to `kenter-crypto`'s `spend_vectors`: those fix the bytes an
//! owner *signs*, these fix which key does the signing. A card and a software
//! wallet derive from the same seed down the same SLIP-0010 path, and the
//! whole owner-key model rests on them landing on the same key — a card that
//! derives differently cannot open the commitments the software wallet wrote,
//! and the notes are stranded with real escrow behind them.
//!
//! This checks that agreement across languages. The applet fork
//! (kenter-keycard, a fork of Status's keycard; `Ed25519.java`) implements
//! SLIP-0010 in JavaCard and otherwise has only its own tests to agree with.
//!
//! The seed is **SEP-0005 test vector 1** — published, so these vectors can be
//! checked against the Stellar ecosystem's own and not only against us.
//!
//! Bless a deliberate change:
//!
//! ```text
//! KENTER_BLESS_VECTORS=1 cargo test -p kenter-vault --test owner_key_vectors
//! ```

use kenter_crypto::keypair::StellarKeypair;
use kenter_crypto::spend::owner_commitment;
use kenter_vault::slip10;
use serde_json::{Value, json};

const VECTORS: &str = "../../tests/vectors/owner_key_vectors.json";

/// BIP-39 seed for SEP-0005 test vector 1.
const SEP5_V1_SEED: &str = "e4a5a632e70943ae7f07659df1332160937fad82587216a4c64315a0fb39497e\
                            e4a01f76ddab4cba68147977f3a147b6ad584c41808e8238a07f6cc4b582f186";

/// The same vector as words \u2014 what a holder actually writes down, and so
/// what a recovery starts from.
///
/// Published here because the card tests need a phrase, not a seed: the
/// claim they check is that a lost card is recoverable from the words, and
/// a test holding its own copy of them is a second place for the pair to
/// drift. `the_phrase_and_the_seed_are_the_same_vector` keeps them honest.
const SEP5_V1_MNEMONIC: &str =
    "illness spike retreat truth genius clock brain pass fit cave bargain toe";

/// Indices worth pinning: the reserved standing tag, the first two rotating
/// tags, and one far enough out to catch a 16-bit truncation.
const INDICES: [u32; 5] = [0, 1, 2, 7, 1000];

fn build() -> Value {
    let seed = hex::decode(SEP5_V1_SEED).expect("seed hex");

    let cases: Vec<Value> = INDICES
        .iter()
        .map(|&index| {
            let secret = slip10::stellar_account_secret(&seed, index).expect("derive");
            let kp = StellarKeypair::from_raw_secret(&secret);
            let pubkey = kp.raw_public();
            json!({
                "index": index,
                "path": format!("m/44'/148'/{index}'"),
                "raw_secret_hex": hex::encode(secret),
                "raw_public_hex": hex::encode(pubkey),
                "stellar_address": kp.stellar_address(),
                "owner_commitment_hex": hex::encode(owner_commitment(&pubkey)),
                "note": if index == 0 {
                    "reserved: the standing pay tag. Rotating tags start at 1."
                } else {
                    ""
                },
            })
        })
        .collect();

    json!({
        "_comment":
            "Generated by crates/kenter-vault/tests/owner_key_vectors.rs. Do not hand-edit: \
             regenerate with KENTER_BLESS_VECTORS=1 cargo test -p kenter-vault --test \
             owner_key_vectors.",
        "consumers": [
            "kenter-keycard — Ed25519.java, on-card SLIP-0010 derivation (JavaCard applet fork)",
            "keycard-shell  — whichever side it asks to derive"
        ],
        "seed": {
            "source": "SEP-0005 test vector 1 (published)",
            "bip39_seed_hex": SEP5_V1_SEED,
            "bip39_mnemonic": SEP5_V1_MNEMONIC,
        },
        "derivation": {
            "scheme": "SLIP-0010 ed25519, all levels hardened",
            "path": "m/44'/148'/n'",
            "note": "The path must match the kenter-keycard fork exactly. A different path \
                     derives keys that cannot open this wallet's commitments, and the failure \
                     mode is silent until a redeem is rejected on-chain.",
        },
        "owner_commitment": "SHA-256( \"kntr_v1:spend:owner\" || raw_public[32] )",
        "cases": cases,
    })
}

/// The two forms of the vector seed must be the same seed.
///
/// Guards the pair at the point it is published rather than at the point it
/// is used, because one of its users puts the phrase **onto a card**: a
/// phrase that did not match would write an unintended key to hardware, and
/// the on-metal test\'s own check against this would be checking a value it
/// had itself taken on trust.
#[test]
fn the_phrase_and_the_seed_are_the_same_vector() {
    let derived = kenter_vault::mnemonic::to_seed(SEP5_V1_MNEMONIC, "").expect("phrase -> seed");
    assert_eq!(
        hex::encode(derived.as_slice()),
        SEP5_V1_SEED,
        "the published phrase and seed are not the same vector"
    );
}

#[test]
fn the_committed_vectors_match_this_crate() {
    let built = serde_json::to_string_pretty(&build()).expect("serializing") + "\n";

    if std::env::var_os("KENTER_BLESS_VECTORS").is_some() {
        std::fs::write(VECTORS, &built).expect("writing vectors");
        return;
    }

    let committed = std::fs::read_to_string(VECTORS)
        .unwrap_or_else(|e| panic!("{VECTORS}: {e}\nGenerate it with KENTER_BLESS_VECTORS=1"));
    let a: Value = serde_json::from_str(&committed).expect("committed vectors are not JSON");
    let b: Value = serde_json::from_str(&built).unwrap();
    if a == b {
        return;
    }
    panic!(
        "\n\nOwner-key derivation changed.\n\n\
         A card deriving the old way can no longer open commitments this wallet \
         writes, and the notes behind them hold real escrow:\n\
         \x20 - kenter-keycard (on-card SLIP-0010)\n\
         \x20 - keycard-shell\n\n\
         If the change is intended:\n\
         \x20 KENTER_BLESS_VECTORS=1 cargo test -p kenter-vault --test owner_key_vectors\n\
         then read the diff on {VECTORS}.\n"
    );
}

/// Index 0 is still the published SEP-0005 address, which is what makes these
/// vectors checkable against someone other than us.
#[test]
fn index_zero_is_the_published_sep5_address() {
    let seed = hex::decode(SEP5_V1_SEED).unwrap();
    let secret = slip10::stellar_account_secret(&seed, 0).unwrap();
    assert_eq!(
        StellarKeypair::from_raw_secret(&secret).stellar_address(),
        "GDRXE2BQUC3AZNPVFSCEZ76NJ3WWL25FYFK6RGZGIEKWE4SOOHSUJUJ6"
    );
}
